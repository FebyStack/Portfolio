-- Chat analytics for the "ask my avatar" chat. Written only by the `ask` edge function (service key, bypasses RLS);
-- read by the owner in the Supabase dashboard. Safe to re-run.

create table if not exists public.chat_logs (
  id uuid primary key,                  -- generated by the edge function and returned to the visitor, so they can rate it
  created_at timestamptz not null default now(),
  session_id uuid,                      -- one per page load (memory only on the client), groups a conversation
  question text not null,
  answer text,                          -- null on error
  status text not null check (status in ('ok', 'error')),
  error_code int,                       -- upstream HTTP status, or null
  model text,
  latency_ms int,
  input_tokens int,
  output_tokens int,
  history_turns smallint,
  referrer text,                        -- domain only
  rating smallint check (rating in (-1, 1)),
  rated_at timestamptz
);
-- ponytail: no index beyond the primary key. Every view and the retention delete scan the table, fine at portfolio
-- volume (hundreds of rows a month). Upgrade: create index on public.chat_logs (created_at) if it gets slow.

-- RLS on with no policies: anon/authenticated get nothing even if a grant slips back in.
alter table public.chat_logs enable row level security;
revoke all on public.chat_logs from anon, authenticated;

-- "unanswered" = the answer contains 'on file'. Superseded by the stored flag in 20261114073833_chat_logs_unanswered.sql,
-- which keeps this match only as the fallback for rows logged before that column existed.

-- Days are Manila days (UTC+8), the owner's timezone.
create or replace view public.chat_daily with (security_invoker = true) as
select
  (created_at at time zone 'Asia/Manila')::date as day,
  count(*) as chats,
  count(distinct session_id) as conversations,
  count(*) filter (where status = 'error') as errors,
  count(*) filter (where answer ilike '%on file%') as unanswered,
  count(*) filter (where rating = 1) as thumbs_up,
  count(*) filter (where rating = -1) as thumbs_down,
  round(avg(latency_ms)) as avg_latency_ms,
  sum(coalesce(input_tokens, 0) + coalesce(output_tokens, 0)) as total_tokens
from public.chat_logs
group by 1
order by 1 desc;

-- What to fix: errors, thumbs down and unanswered questions, newest first.
create or replace view public.chat_review with (security_invoker = true) as
select
  created_at,
  question,
  answer,
  rating,
  coalesce(answer ilike '%on file%', false) as unanswered,
  status
from public.chat_logs
where status = 'error' or rating = -1 or answer ilike '%on file%'
order by created_at desc;

create or replace view public.chat_top_questions with (security_invoker = true) as
select
  lower(trim(question)) as question,
  count(*) as asks,
  max(created_at) as last_asked
from public.chat_logs
group by 1
order by asks desc, last_asked desc;

revoke all on public.chat_daily, public.chat_review, public.chat_top_questions from anon, authenticated;

-- Retention: delete rows older than 180 days, nightly at 03:00 UTC (11:00 Manila).
-- Enable statement per https://supabase.com/docs/guides/cron/install ; scheduling per
-- https://supabase.com/docs/guides/cron/quickstart ("This will replace the existing job via upsert" when the
-- name already exists), so re-running this migration updates the job instead of adding a second one.
create extension if not exists pg_cron with schema pg_catalog;
grant usage on schema cron to postgres;
grant all privileges on all tables in schema cron to postgres;

select cron.schedule(
  'chat-logs-retention',
  '0 3 * * *',
  $$delete from public.chat_logs where created_at < now() - interval '180 days'$$
);
